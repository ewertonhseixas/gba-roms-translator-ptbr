def main():
    lines = MD_FILE.read_text(encoding="utf-8").splitlines()
    updated_lines = []
    translated_count = 0

    for line in lines:
        if not line.startswith("| `") or "---" in line or "ID Script" in line:
            updated_lines.append(line)
            continue

        cols = [c.strip() for c in line.strip("|").split("|")]
        if len(cols) >= 4:
            s_id = cols[0]
            off = cols[1]
            op = cols[2]
            en_text = cols[3]
            pt_text = cols[4] if len(cols) >= 5 else ""

            # Se ainda não traduzido, busca no dicionário
            if not pt_text:
                clean_en = en_text.replace("\\|", "|").strip()
                if clean_en in TRANSLATIONS:
                    pt_text = TRANSLATIONS[clean_en]
                    translated_count += 1
                else:
                    # Tenta correspondência parcial ou pontuações
                    pt_text = ""

            updated_lines.append(f"| {s_id} | {off} | {op} | {en_text} | {pt_text} |")
        else:
            updated_lines.append(line)

    MD_FILE.write_text("\n".join(updated_lines), encoding="utf-8")
    print(f"Tradução aplicada no Lote 01: {translated_count} linhas traduzidas!")


if __name__ == "__main__":
    main()
